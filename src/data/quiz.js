export function scoreAnswers(answers) {
  const counts = {};
  answers.forEach((optionIndex, qi) => {
    const opt = QUESTIONS[qi]?.options[optionIndex];
    if (opt) counts[opt.track] = (counts[opt.track] || 0) + 1;
  });
  let best = TRACK_ORDER[0];
  for (const t of TRACK_ORDER) if ((counts[t] || 0) > (counts[best] || 0)) best = t;
  return best;
}
